// `/coming-soon` is served as an STX view from
// `storage/framework/defaults/resources/views/coming-soon.stx`. The
// view auto-resolves through stx-serve, so no route registration is
// needed here. To activate the holding page across the whole app:
//
//   ./buddy coming-soon [--secret=my-magic-token]
//
// Launch the site with `./buddy launch`. Maintenance mode (503 page,
// distinct cookie + state file) is the separate `./buddy down` /
// `./buddy up` pair.

// The desktop app's update feed. Mounted here by name so it is served whatever
// STACKS_DEFAULT_ROUTES says: production runs with the default bundles off.
route.get('/updates/{platform}/{arch}', 'Actions/Desktop/UpdateFeedAction')
// A published build, streamed from the updates disk: what the feed's manifests and the download page link to.
route.get('/updates/files/{channel}/{target}/{version}/{file}', 'Actions/Desktop/UpdateArtifactAction')
// The newest build for a platform, as a redirect. The site's download button points here.
route.get('/download/{platform}', 'Actions/Desktop/LatestDownloadAction')
